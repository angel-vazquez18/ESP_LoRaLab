const fs=require('node:fs');
const path=require('node:path');
const dir=__dirname;
const template=fs.readFileSync(path.join(dir,'ptt-cutaway-animation.template.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(dir,'ptt-cutaway-meshes.json'),'utf8'));
const contact=JSON.parse(fs.readFileSync(path.join(dir,'ptt-contact-patch.json'),'utf8'));
const loadPath=JSON.parse(fs.readFileSync(path.join(dir,'ptt-load-path.json'),'utf8'));
const html=template.replace('__PTT_CUTAWAY_MESH_JSON__',JSON.stringify(data).replace(/</g,'\\u003c')).replace('__PTT_CONTACT_PATCH_JSON__',JSON.stringify(contact).replace(/</g,'\\u003c')).replace('__PTT_LOAD_PATH_JSON__',JSON.stringify(loadPath).replace(/</g,'\\u003c'));
if(Buffer.byteLength(html)>=1048576)throw new Error('Visualization exceeds1 MiB');
fs.writeFileSync(path.join(dir,'ptt-cutaway-animation.html'),html);
console.log(JSON.stringify({path:path.join(dir,'ptt-cutaway-animation.html'),bytes:Buffer.byteLength(html),parts:data.parts.length}));
